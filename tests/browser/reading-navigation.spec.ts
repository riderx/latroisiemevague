import { test, expect } from '@playwright/test'

test('contents track manual scrolling, deep links and history in both guide categories', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const path of ['/substances/lsd/', '/microdosing/lsd/']) {
    await page.goto(path + '#overview')
    const toc = page.locator('.reader-toc')
    const active = toc.locator('a[aria-current="location"]')
    await expect(active).toHaveAttribute('href', '#overview')
    await expect(toc.locator('summary')).toBeInViewport()
    const early = await toc.locator('progress').evaluate(el => (el as HTMLProgressElement).value)
    await page.locator('#effects').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + window.scrollY + 80))
    await expect(active).toHaveAttribute('href', '#effects')
    expect(await toc.locator('progress').evaluate(el => (el as HTMLProgressElement).value)).toBeGreaterThan(early)
    await expect(toc.locator('a[href="#overview"]')).toHaveClass(/is-read/)
    await expect(active).toBeInViewport()
    await toc.locator('a[href="#faq"]').click()
    await expect(page).toHaveURL(/#faq$/)
    await expect(active).toHaveAttribute('href', '#faq')
    await page.goBack()
    await expect(page).toHaveURL(/#overview$/)
    await page.locator('#overview').evaluate(el => el.scrollIntoView())
    await expect(active).toHaveAttribute('href', '#overview')
    await page.locator('#source-originale').evaluate(el => el.scrollIntoView())
    await expect(active).toHaveAttribute('href', '#source-originale')
    await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
    await expect(toc.locator('progress')).toHaveJSProperty('value', 100)
  }
  await page.goto('/substances/lsd/#effects')
  await expect(page.locator('.reader-toc a[aria-current="location"]')).toHaveAttribute('href', '#effects')
  await page.screenshot({ path: 'output/reader-desktop-scroll.png' })
})

test('mobile contents stay visible, close after navigation and respect reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/microdosing/champignons-psilocybin/')
    const toc = page.locator('.reader-toc')
    const details = toc.locator('details')
    await expect(toc).toHaveAttribute('data-enhanced', 'true')
    await expect(details).not.toHaveAttribute('open')
    await page.locator('#effects').evaluate(el => el.scrollIntoView())
    await expect(toc.locator('a[aria-current="location"]')).toHaveAttribute('href', '#effects')
    await expect(toc.locator('summary')).toBeInViewport()
    expect((await toc.boundingBox())!.y).toBeGreaterThanOrEqual(9)
    expect((await toc.boundingBox())!.y).toBeLessThanOrEqual(11)
    await toc.locator('summary').click()
    await expect(details).toHaveAttribute('open')
    await toc.locator('a[href="#history"]').click()
    await expect(details).not.toHaveAttribute('open')
    await expect(toc.locator('a[aria-current="location"]')).toHaveAttribute('href', '#history')
    expect((await page.locator('#history').boundingBox())!.y).toBeGreaterThan((await toc.boundingBox())!.y + (await toc.boundingBox())!.height)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior)).toBe('auto')
    await toc.locator('summary').click()
    await page.keyboard.press('Escape')
    await expect(details).not.toHaveAttribute('open')
    await expect(toc.locator('summary')).toBeFocused()
  }
  await page.screenshot({ path: 'output/reader-mobile-scroll.png' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(page.locator('.reader-toc details')).toHaveAttribute('open')
})

test('guide contents and full article remain usable without JavaScript', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, baseURL: 'http://127.0.0.1:4321' })
  const page = await context.newPage()
  await page.goto('/substances/ibogaine/')
  await expect(page.locator('.reader-toc details')).toHaveAttribute('open')
  await page.locator('.reader-toc a[href="#footnotes"]').click()
  await expect(page).toHaveURL(/#footnotes$/)
  await expect(page.locator('#footnotes')).toBeInViewport()
  await expect(page.locator('.guide-translated-content')).toContainText('ibogaïne')
  await context.close()
})
